import { readFileSync } from 'node:fs';
import { CityDex, decodeCities } from '../app/src/data/cities.ts';
const load = (p) => decodeCities(JSON.parse(readFileSync(p, 'utf8')));
const pts = [...load('app/public/data/cities.json'), ...load('app/public/data/cities_fulda.json')];
const dex = new CityDex(pts);
const nearList = dex.near([9.6, 50.5, 9.8, 50.6]);
console.log('near count', nearList.length, nearList.slice(0, 5));
console.log('nearest', dex.nearest(9.675, 50.552));
const f = pts.filter((p) => Math.abs(p.lon - 9.675) < 0.02 && Math.abs(p.lat - 50.552) < 0.02);
console.log('fulda recs', f);
